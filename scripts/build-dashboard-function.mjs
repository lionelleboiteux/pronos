#!/usr/bin/env node
// Regenerates supabase/functions/dashboard/index.ts from dashboard/index.html.
//
// dashboard/index.html is the single source of truth (and the artifact
// john-dashboard expects at that exact path). Supabase's bundler rejects the
// `with { type: "text" }` import attribute that would let the Edge Function
// import the HTML file directly, and public Storage silently downgrades
// `.html` objects to `text/plain` (an XSS-prevention default), so it won't
// render as a page either. Embedding the HTML as a string is the option
// that's actually been verified to work — see 11-dashboard.v1.md.
//
// Run this, then `supabase functions deploy dashboard`, any time
// dashboard/index.html changes.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const repoRoot = path.resolve(fileURLToPath(import.meta.url), '..', '..');
const htmlPath = path.join(repoRoot, 'dashboard', 'index.html');
const outPath = path.join(repoRoot, 'supabase', 'functions', 'dashboard', 'index.ts');

const html = readFileSync(htmlPath, 'utf8');
if (html.includes('`') || html.includes('${')) {
  throw new Error(
    'dashboard/index.html contains a backtick or ${ — unsafe to embed as-is in a template literal. Update this script to escape it.',
  );
}

const generated = `/**
 * GENERATED by scripts/build-dashboard-function.mjs — do not edit directly.
 * Source of truth is dashboard/index.html; re-run that script after
 * changing it, then \`supabase functions deploy dashboard\`.
 */
const DASHBOARD_HTML = \`${html}\`;

Deno.serve(() => new Response(DASHBOARD_HTML, { headers: { 'content-type': 'text/html; charset=utf-8' } }));
`;

writeFileSync(outPath, generated);
console.log(`Wrote ${path.relative(repoRoot, outPath)} from ${path.relative(repoRoot, htmlPath)}`);
